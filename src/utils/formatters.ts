import JSZip from 'jszip';
import { BibEntry, DocumentBlock, DocumentConfig } from '../types/document';
import {
  serializeBibToBibtex,
  serializeDocumentToLatex,
} from '../engine/latexSerializer';

const pluralRules = new Intl.PluralRules('en-US');
const numberFormat = new Intl.NumberFormat('en-US');

/**
 * Proper pluralization using Intl.PluralRules (Emil Kowalski ui-cheatsheet.md)
 * Never outputs "1 words" or "1 issues".
 */
export function formatCount(count: number, singular: string, plural?: string): string {
  const safeCount = Number.isFinite(count) ? count : 0;
  const rule = pluralRules.select(safeCount);
  const word = rule === 'one' ? singular : (plural ?? `${singular}s`);
  return `${numberFormat.format(safeCount)} ${word}`;
}

export function formatNumber(value: number): string {
  if (!Number.isFinite(value)) return '0';
  return numberFormat.format(value);
}

/**
 * Extracts safe grapheme-cluster initials using Intl.Segmenter (Emil Kowalski break-ui SKILL.md)
 * Handles 1-letter names ("J"), emoji names ("🦊 Fox"), CJK, and hyphenated names cleanly.
 */
export function getSafeInitials(fullName: string): string {
  const cleaned = (fullName || '').trim();
  if (!cleaned) return 'AU';

  const words = cleaned.split(/\s+/).filter(Boolean);
  const getFirstGrapheme = (str: string): string => {
    if (typeof Intl !== 'undefined' && 'Segmenter' in Intl) {
      const segmenter = new Intl.Segmenter('en', { granularity: 'grapheme' });
      const first = segmenter.segment(str)[Symbol.iterator]().next().value;
      return first?.segment ?? str.slice(0, 1);
    }
    return Array.from(str)[0] ?? '';
  };

  if (words.length === 1) {
    return getFirstGrapheme(words[0]).toUpperCase();
  }
  const first = getFirstGrapheme(words[0]);
  const last = getFirstGrapheme(words[words.length - 1]);
  return `${first}${last}`.toUpperCase();
}

export function downloadTextFile(
  filename: string,
  content: string,
  mimeType = 'text/plain;charset=utf-8'
): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Generates and downloads a complete Overleaf & arXiv compatible .zip project bundle
 * containing main.tex, references.bib, and build instructions.
 */
export async function exportOverleafZipBundle(
  config: DocumentConfig,
  blocks: DocumentBlock[],
  bibliography: BibEntry[]
): Promise<void> {
  const zip = new JSZip();
  const mainTex = serializeDocumentToLatex(config, blocks, bibliography);
  const bibTex = serializeBibToBibtex(bibliography);

  zip.file('main.tex', mainTex);
  zip.file('references.bib', bibTex);
  zip.file(
    'README.md',
    `# ${config.title}\n\nGenerated by **OmniTeX Studio**.\n\n## How to Compile\n- **Overleaf:** Upload this \`.zip\` directly via *New Project -> Upload Project*.\n- **Local TeX Live / Tectonic:** Run \`pdflatex main.tex && bibtex main && pdflatex main.tex && pdflatex main.tex\` or \`tectonic main.tex\`.\n`
  );

  const blob = await zip.generateAsync({ type: 'blob' });
  const slug =
    config.title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .slice(0, 40) || 'omnitex-project';

  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${slug}-overleaf.zip`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
